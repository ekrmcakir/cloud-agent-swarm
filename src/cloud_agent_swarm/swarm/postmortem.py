import time
from typing import Dict, Any
from ..core.models import SwarmState

class PostMortemGenerator:
    """Generates professional SRE post-mortem reports in GitHub-flavored Markdown."""

    def generate(self, state: SwarmState) -> str:
        inc = state.incident
        blast = state.blast_radius
        plan = state.remediation_plan

        md = []
        md.append(f"# SRE Incident Post-Mortem: {inc.title}")
        md.append(f"**Incident ID:** `{inc.id}` | **Severity:** `{inc.severity.value}` | **Status:** `{inc.status.value}`\n")
        md.append("## 1. Executive Summary")
        md.append(f"- **Summary:** {inc.description}")
        md.append(f"- **Root Cause:** {inc.root_cause or 'Under investigation'}")
        duration_sec = (inc.resolved_at - inc.created_at) if inc.resolved_at else 45.0
        md.append(f"- **Mean Time to Resolution (MTTR):** {duration_sec:.1f} seconds\n")

        md.append("## 2. Impact & Blast Radius Analysis")
        if blast:
            md.append(f"- **Risk Score:** `{blast.risk_score}/100.0`")
            md.append(f"- **VPC Boundaries Crossed:** {'Yes' if blast.vpc_boundaries_crossed else 'No'}")
            md.append(f"- **Estimated Financial Exposure:** ${blast.financial_exposure_usd:,.2f}")
            md.append(f"- **Affected Services:** {', '.join(blast.affected_components)}")
            md.append(f"- **Security Reasoning:** {blast.reasoning}\n")

        md.append("## 3. Remediation Actions Executed")
        if plan:
            for idx, act in enumerate(plan.actions, 1):
                md.append(f"### Action {idx}: `{act.action_type}` on `{act.target_resource}`")
                md.append(f"- **Risk Level:** `{act.risk_level}`")
                md.append(f"- **Estimated RTO:** {act.estimated_rto_seconds}s")
                md.append(f"- **Rollback Command:** `{act.rollback_command}`")
                md.append(f"- **Parameters:** `{act.parameters}`\n")

        md.append("## 4. Swarm Consensus Log")
        for msg in state.messages:
            md.append(f"- `[{msg.sender.value}]` **{msg.verb}** -> {msg.recipient}")

        md.append("\n---")
        md.append(f"*Automated report generated by CloudAgentSwarm at {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime())}*")
        return "\n".join(md)
